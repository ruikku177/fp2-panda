const studyGlossaryTerms=Object.create(null);
const studyGlossaryLessons=Object.create(null);
function registerStudyTerms(_group,rows){
  for(const [name,meaning,example,contrast='',aliases=[]] of rows){
    if(studyGlossaryTerms[name])throw new Error(`Duplicate study term: ${name}`);
    studyGlossaryTerms[name]={name,meaning,example,contrast,aliases};
  }
}
function bindStudyTerms(chapter,theme,rows){
  for(const [lesson,names] of rows){
    const key=`${chapter}:${theme}:${lesson}`;
    if(studyGlossaryLessons[key])throw new Error(`Duplicate term binding: ${key}`);
    studyGlossaryLessons[key]=names.split('|');
  }
}
